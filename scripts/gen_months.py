#!/usr/bin/env python3
"""Generate src/months.rs (the BS month-length table) from data/bs-calendar.json.

Usage: scripts/gen_months.py   then `cargo build`.
"""
import datetime
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
cal = json.loads((ROOT / "data" / "bs-calendar.json").read_text())
first, last = cal["min_year"], cal["max_year"]
rows = [cal["month_lengths"][str(y)] for y in range(first, last + 1)]
assert len(rows) == len(cal["month_lengths"]), "gap in years"
assert all(len(r) == 12 and all(29 <= n <= 32 for n in r) for r in rows)

assert cal["epoch"]["bs"] == f"{first}-01-01"
epoch = (datetime.date.fromisoformat(cal["epoch"]["ad"]) - datetime.date(1970, 1, 1)).days

body = "\n".join(f"    {r}, // {first + i}" for i, r in enumerate(rows))
(ROOT / "src" / "months.rs").write_text(
    "// Generated by scripts/gen_months.py from data/bs-calendar.json (see data/NOTICE). Do not edit.\n"
    f"pub const FIRST_YEAR: u16 = {first};\n"
    "/// Days from 1970-01-01 AD to Baisakh 1 of FIRST_YEAR (negative: before 1970).\n"
    f"pub const EPOCH: i32 = {epoch};\n"
    f"pub static MONTHS: [[u8; 12]; {len(rows)}] = [\n{body}\n];\n"
)
print(f"{len(rows)} years, {first}-{last}, epoch {epoch}")
